# Numpy - ndarray
import numpy as np # importa una biblioteca numpy e attribusce un nome più corto (np) per facilitarne l'utilizzo

arr = np.array([1, 2, 3, 4, 5]) # crea u narray unidimensionale (1D) con elementi 1, 2, 3, 4 e 5

arr2d = np.array([[1, 2, 3], [4, 5, 6]]) # crea un array bidimensionale (2D) con elementi 1, 2, 3 na prima riga e 4, 5, 6 na seconda riga

print(arr)
print(arr2d) 